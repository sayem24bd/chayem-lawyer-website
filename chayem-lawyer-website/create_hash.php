<?php

// ১. এখানে আপনার আসল পাসওয়ার্ডটি লিখুন:
$passwordToHash = 'Sayem0857@#'; // উদাহরণস্বরূপ 'sayem12345' ব্যবহার করা হলো। আপনি আপনার শক্তিশালী পাসওয়ার্ড দিন।

// ২. পাসওয়ার্ড হ্যাশ তৈরি করা:
// PASSWORD_DEFAULT বর্তমানে bcrypt ব্যবহার করে, যা নিরাপদ।
$hashedPassword = password_hash($passwordToHash, PASSWORD_DEFAULT);

// ৩. ফলাফল দেখানো (শুধুমাত্র ডেভেলপমেন্টের জন্য):
echo "Username: admin<br>"; // যে ইউজারনেমের জন্য হ্যাশ তৈরি করছেন
echo "Password Used: " . htmlspecialchars($passwordToHash) . "<br>"; // কোন পাসওয়ার্ড ব্যবহার করা হয়েছে তা দেখানো (নিরাপত্তার জন্য পরে মুছে দিন)
echo "Generated Password Hash (এই হ্যাশটি কপি করুন):<br>";
echo "<b>" . htmlspecialchars($hashedPassword) . "</b>"; // হ্যাশটি বোল্ড করে দেখানো

/*
গুরুত্বপূর্ণ:
- এই ফাইলটি শুধুমাত্র হ্যাশ তৈরি করার জন্য ব্যবহার করুন।
- হ্যাশটি তৈরি হয়ে গেলে এবং আপনি সেটি ডেটাবেসে বসিয়ে দিলে, এই ফাইলটি সার্ভার থেকে মুছে ফেলুন অথবা অ্যাক্সেস বন্ধ করে দিন।
- $passwordToHash ভ্যারিয়েবলে একটি শক্তিশালী, ইউনিক পাসওয়ার্ড ব্যবহার করুন।
*/

?>